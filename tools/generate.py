# ------------------------------------------------------------------ helpers
def php(v):
    if v is None:
        return 'null'
    if v is True:
        return 'true'
    if v is False:
        return 'false'
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return "'" + v.replace('\\', '\\\\').replace("'", "\\'") + "'"
    if isinstance(v, (list, tuple)):
        return '[' + ', '.join(php(x) for x in v) + ']'
    if isinstance(v, dict):
        return '[' + ', '.join(f'{php(k)} => {php(x)}' for k, x in v.items()) + ']'
    raise TypeError(v)


def camel(name):
    base = name[:-3] if name.endswith('_id') else name
    parts = base.split('_')
    return parts[0] + ''.join(p.title() for p in parts[1:])


def rel_key(name):
    return name[:-3] if name.endswith('_id') else name


def label_of(fld):
    if fld.get('label'):
        return fld['label']
    return rel_key(fld['name']).replace('_', ' ').capitalize()


def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


